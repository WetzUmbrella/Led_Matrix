#!/usr/bin/env python3
"""List every test case of one host test run with its verdict.

Usage:
    python3 tools/test_cases.py docs/testing/results/2026-11-25

Reads the logs that tools/run_all_tests.sh wrote into that folder and writes
CASES.md beside them: one table per C suite (each case's name, which states
its input and expected output, and PASS or FAIL as the test printed it) and
one table per pytest file (every test function and its verdict).

C suites print a case name on an unindented line and its verdict on an
indented "PASS" or "FAIL" line. The Pico suite also prints the
coordinator's own log lines (CL_EVENT, CL_STATS and histograms) between
them; those are skipped. Exit status 1 when a case failed or a log is
missing.
"""

from __future__ import annotations

import os
import re
import sys
from typing import Dict, List, Tuple

#: (log file without .log, title) of the C suites, plain builds.
C_SUITES = [
    ("common_proto", "common/proto: message packing (C)"),
    ("panel_sync", "panel_sync: tile modules (C)"),
    ("ledwall_sync", "ledwall_sync: Pico coordinator and game rules (C)"),
    ("tools_pico_tap", "tools/pico_tap: tap logger ring (C)"),
]

#: Unindented lines that are not case names: make and the coordinator's log.
NOISE = re.compile(r"^(make|\./|gcc|cc |CL_|COORDINATOR|LATE_HIST|"
                   r"CB_HIST|DISPATCH_HIST)|Pass = \d+ of \d+")
VERDICT = re.compile(r"^\s+(PASS|FAIL)\s*$")
PYTEST = re.compile(r"^(\S+?\.py)::(.+?) (PASSED|FAILED|SKIPPED|ERROR)\b")


def c_cases(path: str) -> List[Tuple[str, str]]:
    """(case name, PASS or FAIL) in the order the suite ran them."""
    cases: List[Tuple[str, str]] = []
    name = ""
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.rstrip("\n")
            verdict = VERDICT.match(line)
            if verdict and name:
                cases.append((name, verdict.group(1)))
                name = ""
            elif line and not line[0].isspace() and not NOISE.search(line):
                name = line.strip()
    return cases


def py_cases(path: str) -> Dict[str, List[Tuple[str, str]]]:
    """pytest file -> [(test id, verdict)] from a verbose run."""
    files: Dict[str, List[Tuple[str, str]]] = {}
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            match = PYTEST.match(line)
            if match:
                files.setdefault(match.group(1), []).append(
                    (match.group(2), match.group(3)))
    return files


def cell(text: str) -> str:
    """Text safe inside a Markdown table cell."""
    return text.replace("|", "/")


def main(argv: List[str]) -> int:
    """Write CASES.md for the results folder in argv[1]."""
    if len(argv) != 2:
        print(__doc__.strip().splitlines()[2].strip(), file=sys.stderr)
        return 2
    folder = argv[1]
    failed = 0
    lines = ["# Test cases, one row each", "",
             "Generated by `tools/test_cases.py` from the logs in this "
             "folder. A C case's name states what goes in and what must come "
             "out; its log shows the values the test printed on the way. The "
             "ASan and UBSan runs of each C suite (`*_asan.log`) run the same "
             "cases.", ""]

    for log, title in C_SUITES:
        path = os.path.join(folder, log + ".log")
        if not os.path.exists(path):
            print("missing %s" % path, file=sys.stderr)
            return 1
        cases = c_cases(path)
        bad = sum(1 for _, verdict in cases if verdict != "PASS")
        failed += bad
        lines += ["## %s" % title, "",
                  "%d cases, %d failed. Log: `%s.log`." % (
                      len(cases), bad, log), "",
                  "| # | Case | Result |", "|---|---|---|"]
        lines += ["| %d | %s | %s |" % (index, cell(name), verdict)
                  for index, (name, verdict) in enumerate(cases, start=1)]
        lines.append("")

    path = os.path.join(folder, "pytest.log")
    if not os.path.exists(path):
        print("missing %s" % path, file=sys.stderr)
        return 1
    files = py_cases(path)
    total = sum(len(tests) for tests in files.values())
    lines += ["## pytest: website, GIF build, upload, protocol, tools "
              "(Python)", "",
              "%d tests in %d files. Log: `pytest.log`." % (
                  total, len(files)), ""]
    for name in sorted(files):
        tests = files[name]
        bad = sum(1 for _, verdict in tests if verdict in ("FAILED", "ERROR"))
        failed += bad
        lines += ["### `%s` (%d)" % (name, len(tests)), "",
                  "| Test | Result |", "|---|---|"]
        lines += ["| `%s` | %s |" % (cell(test), verdict)
                  for test, verdict in tests]
        lines.append("")

    with open(os.path.join(folder, "CASES.md"), "w",
              encoding="utf-8") as handle:
        handle.write("\n".join(lines))
    print("wrote %s: %d failed" % (os.path.join(folder, "CASES.md"), failed))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
