"""pytest suite for pc/tools/skew_analyse.py on synthetic captures.

Each case runs on three synthetic exports of the same signals:
  saleae        Saleae Logic 2 digital CSV (one row per change, first row is
                the initial state);
  sigrok_time   sigrok CSV with header comments, label=channel, time=true,
                dedup=true (time column in microseconds at 1 MHz);
  sigrok_rows   sigrok CSV with label=units (columns labelled 'logic'), no time
                column, one row per sample at 100 kHz, rate from the comment.
"""

import csv
import os
import sys

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "tools"))
import skew_analyse as sa  # noqa: E402

TICK_US = 1_000_000 / 60
PULSE_US = 1_000          # synthetic pulse width (test value)
START_US = 3_000          # first tick in the synthetic capture (test value)
N_TICKS = 40
END_US = START_US + N_TICKS * TICK_US + 2_000


def pulses(skew_us, drop=None, extra_high_at_start=False):
    """Return two lists of (rise_us, fall_us) intervals for channels A and B.
    Rises are rounded to 10 us so that the 100 kHz sample grid holds them."""
    def grid(t):
        return round(t / 10) * 10

    a, b = [], []
    for n in range(N_TICKS):
        ta = grid(START_US + n * TICK_US)
        a.append((ta, ta + PULSE_US))
        if drop is None or n != drop:
            b.append((ta + skew_us, ta + skew_us + PULSE_US))
    if extra_high_at_start:
        # Both pins already high when the capture starts (mid-pulse).
        a.insert(0, (0, 500))
        b.insert(0, (0, 700))
    return a, b


def level(intervals, t):
    return 1 if any(r <= t < f for r, f in intervals) else 0


def change_times(a, b):
    ts = {0}
    for r, f in a + b:
        ts.add(r)
        ts.add(f)
    return sorted(t for t in ts if t < END_US)


def write_saleae(path, a, b):
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["Time [s]", "Channel 0", "Channel 1"])
        for t in change_times(a, b):
            w.writerow([f"{t / 1e6:.9f}", level(a, t), level(b, t)])
    return "Channel 0", "Channel 1"


def sigrok_comments(f, rate_text):
    f.write("; CSV generated by libsigrok 0.5.2\n")
    f.write("; from fx2lafw on Thu Oct 22 10:00:00 2026\n")
    f.write("; Channels (2/8): D0, D1\n")
    f.write(f"; Samplerate: {rate_text}\n")


def write_sigrok_time(path, a, b):
    with open(path, "w", newline="") as f:
        sigrok_comments(f, "1 MHz")
        f.write("Time,D0,D1\n")
        for t in change_times(a, b):
            f.write(f"{int(t)},{level(a, t)},{level(b, t)}\n")
    return "D0", "D1"


def write_sigrok_rows(path, a, b):
    rate = 100_000
    step = 1e6 / rate
    with open(path, "w", newline="") as f:
        sigrok_comments(f, "100 kHz")
        f.write("logic,logic\n")
        n = 0
        while n * step < END_US:
            t = n * step
            f.write(f"{level(a, t)},{level(b, t)}\n")
            n += 1
    return "D0", "D1"


WRITERS = {"saleae": write_saleae, "sigrok_time": write_sigrok_time,
           "sigrok_rows": write_sigrok_rows}


def run(tmp_path, kind, a, b, extra=()):
    cap = tmp_path / f"{kind}.csv"
    out = tmp_path / f"{kind}_pairs.csv"
    ch_a, ch_b = WRITERS[kind](cap, a, b)
    rc = sa.main([str(cap), "--ch-a", ch_a, "--ch-b", ch_b, "--out", str(out), *extra])
    with open(out) as f:
        rows = list(csv.DictReader(f))
    return rc, rows


@pytest.mark.parametrize("kind", list(WRITERS))
def test_format_autodetect(tmp_path, kind):
    cap = tmp_path / "c.csv"
    WRITERS[kind](cap, *pulses(1_000))
    with open(cap) as f:
        lines = f.read().splitlines()
    assert sa.detect_format(lines) == ("saleae" if kind == "saleae" else "sigrok")


@pytest.mark.parametrize("kind", list(WRITERS))
def test_clean_1ms_skew_passes(tmp_path, kind, capsys):
    rc, rows = run(tmp_path, kind, *pulses(1_000))
    text = capsys.readouterr().out
    assert rc == sa.EXIT_PASS
    assert len(rows) == N_TICKS
    assert all(abs(float(r["skew_ms"]) - 1.0) < 1e-6 for r in rows)
    assert "max_abs_skew_ms=1.000" in text
    assert "median_abs_skew_ms=1.000" in text
    assert "p99_abs_skew_ms=1.000" in text
    assert "UNPAIRED" not in text
    assert "VERDICT: PASS" in text
    assert [int(r["tick"]) for r in rows] == list(range(N_TICKS))


@pytest.mark.parametrize("kind", list(WRITERS))
def test_6ms_skew_fails(tmp_path, kind, capsys):
    rc, rows = run(tmp_path, kind, *pulses(6_000))
    text = capsys.readouterr().out
    assert rc == sa.EXIT_FAIL
    assert len(rows) == N_TICKS
    assert "max_abs_skew_ms=6.000" in text
    assert "VERDICT: FAIL" in text


@pytest.mark.parametrize("kind", list(WRITERS))
def test_dropped_edge_logged_and_others_paired(tmp_path, kind, capsys):
    drop = 17
    rc, rows = run(tmp_path, kind, *pulses(1_000, drop=drop))
    text = capsys.readouterr().out
    unpaired = [l for l in text.splitlines() if l.startswith("UNPAIRED")]
    assert len(unpaired) == 1
    assert f"tick={drop}" in unpaired[0]
    assert "channel=" + ("Channel 0" if kind == "saleae" else "D0") in unpaired[0]
    assert len(rows) == N_TICKS - 1
    ticks = [int(r["tick"]) for r in rows]
    assert ticks == [n for n in range(N_TICKS) if n != drop]
    assert all(abs(float(r["skew_ms"]) - 1.0) < 1e-6 for r in rows)
    assert rc == sa.EXIT_PASS


@pytest.mark.parametrize("kind", list(WRITERS))
def test_capture_starting_mid_pulse(tmp_path, kind, capsys):
    a, b = pulses(1_000, extra_high_at_start=True)
    rc, rows = run(tmp_path, kind, a, b)
    text = capsys.readouterr().out
    assert rc == sa.EXIT_PASS
    assert len(rows) == N_TICKS
    assert "UNPAIRED" not in text
    assert f"edges_a={N_TICKS} edges_b={N_TICKS}" in text
    assert min(float(r["t_a_s"]) for r in rows) == pytest.approx(START_US / 1e6)


def toggles(skew_us, b_inverted):
    """Toggling test pins (T-B5-01: the ISR toggles the pin each tick).
    A is high from tick 2k to 2k+1; B is the same shifted by skew_us, and
    inverted (high from 2k+1 to 2k+2) when b_inverted is set."""
    def grid(t):
        return round(t / 10) * 10

    a, b = [], []
    for k in range(N_TICKS // 2):
        r = grid(START_US + 2 * k * TICK_US)
        f = grid(START_US + (2 * k + 1) * TICK_US)
        a.append((r, f))
        if b_inverted:
            b.append((f + skew_us, grid(START_US + (2 * k + 2) * TICK_US) + skew_us))
        else:
            b.append((r + skew_us, f + skew_us))
    return a, b


@pytest.mark.parametrize("inverted", [False, True])
def test_both_edges_mode_on_toggling_pins(tmp_path, capsys, inverted):
    a, b = toggles(1_000, inverted)
    rc, rows = run(tmp_path, "saleae", a, b, extra=("--edges", "both"))
    text = capsys.readouterr().out
    assert rc == sa.EXIT_PASS
    assert all(abs(float(r["skew_ms"]) - 1.0) < 1e-6 for r in rows)
    assert "max_abs_skew_ms=1.000" in text
    assert ("NOTE:" in text) == inverted


def test_p99_nearest_rank():
    vals = sorted(float(v) for v in range(1, 201))   # 1..200
    assert sa.p99_nearest_rank(vals) == 198.0        # rank ceil(0.99 x 200) = 198
    assert sa.p99_nearest_rank([5.0]) == 5.0


def test_bad_input(tmp_path, capsys):
    cap = tmp_path / "bad.csv"
    cap.write_text("Time [s],Channel 0,Channel 1\n0.0,0,0\n")
    assert sa.main([str(cap), "--ch-a", "Channel 0", "--ch-b", "Channel 9",
                    "--out", str(tmp_path / "o.csv")]) == sa.EXIT_BAD_INPUT
    cap.write_text("D0,D1\n0,0\n1,1\n")       # no time column, no sample rate
    assert sa.main([str(cap), "--ch-a", "D0", "--ch-b", "D1",
                    "--out", str(tmp_path / "o.csv")]) == sa.EXIT_BAD_INPUT
    assert sa.main([str(tmp_path / "missing.csv"), "--ch-a", "D0", "--ch-b", "D1"]) \
        == sa.EXIT_BAD_INPUT


def test_plot_written(tmp_path, capsys):
    pytest.importorskip("matplotlib")
    cap = tmp_path / "c.csv"
    write_saleae(cap, *pulses(1_000))
    png = tmp_path / "skew.png"
    rc = sa.main([str(cap), "--ch-a", "Channel 0", "--ch-b", "Channel 1",
                  "--out", str(tmp_path / "p.csv"), "--plot", str(png)])
    assert rc == sa.EXIT_PASS
    assert png.stat().st_size > 0
