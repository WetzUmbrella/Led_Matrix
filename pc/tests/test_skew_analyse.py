def toggles(skew_us, b_inverted):
    """Toggling test pins (T-B5-01: the ISR toggles the pin each tick).
    A is high from tick 2k to 2k+1; B is the same shifted by skew_us, and
    inverted (high from 2k+1 to 2k+2) when b_inverted is set."""
    def grid(t):
        return round(t / 10) * 10

    a, b = [], []
    for k in range(N_TICKS // 2):
        r = grid(START_US + 2 * k * TICK_US)
        f = grid(START_US + (2 * k + 1) * TICK_US)
        a.append((r, f))
        if b_inverted:
            b.append((f + skew_us, grid(START_US + (2 * k + 2) * TICK_US) + skew_us))
        else:
            b.append((r + skew_us, f + skew_us))
    return a, b


@pytest.mark.parametrize("inverted", [False, True])
def test_both_edges_mode_on_toggling_pins(tmp_path, capsys, inverted):
    a, b = toggles(1_000, inverted)
    rc, rows = run(tmp_path, "saleae", a, b, extra=("--edges", "both"))
    text = capsys.readouterr().out
    assert rc == sa.EXIT_PASS_CONDITIONAL
    assert all(abs(float(r["skew_ms"]) - 1.0) < 1e-6 for r in rows)
    assert "max_abs_skew_ms=1.000" in text
    assert ("NOTE:" in text) == inverted


def test_p99_nearest_rank():
    vals = sorted(float(v) for v in range(1, 201))   # 1..200
    assert sa.p99_nearest_rank(vals) == 198.0        # rank ceil(0.99 x 200) = 198
    assert sa.p99_nearest_rank([5.0]) == 5.0


